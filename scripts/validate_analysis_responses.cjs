#!/usr/bin/env node
// Validate serialized .NET responses, complementing the route-only Python gate.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { createRequire } = require('node:module');
const root = path.resolve(__dirname, '..');
const webRequire = createRequire(path.join(root, 'src/web/aura-web/package.json'));
const yaml = webRequire('js-yaml');
const Ajv = webRequire('ajv');
const addFormats = webRequire('ajv-formats');

function normalize(value) {
  if (Array.isArray(value)) return value.map(normalize);
  if (!value || typeof value !== 'object') return value;
  const result = Object.fromEntries(Object.entries(value).filter(([key]) => key !== 'nullable')
    .map(([key, child]) => [key, normalize(child)]));
  // OpenAPI 3.0 uses boolean exclusivity; Ajv's JSON Schema draft uses numeric bounds.
  for (const [exclusive, bound] of [['exclusiveMinimum', 'minimum'], ['exclusiveMaximum', 'maximum']]) {
    if (typeof value[exclusive] !== 'boolean') continue;
    delete result[exclusive];
    if (value[exclusive] && typeof value[bound] === 'number') {
      result[exclusive] = value[bound];
      delete result[bound];
    }
  }
  return value.nullable ? { anyOf: [result, { type: 'null' }] } : result;
}

const contract = normalize(yaml.load(fs.readFileSync(path.join(root, 'contracts/analysis-openapi-0.9.yaml'), 'utf8')));
const ajv = new Ajv({ allErrors: true, strict: false });
addFormats(ajv);
ajv.addFormat('binary', true);
ajv.addSchema(contract, 'aura-analysis');

function properties(schema) {
  if (schema.$ref) return properties(schema.$ref.split('/').slice(1).reduce((node, key) => node[key], contract));
  return Object.assign({}, schema.properties, ...(schema.allOf || schema.anyOf || []).map(properties));
}

function validate(sample) {
  const schema = contract.components.schemas[sample.schema];
  if (!schema) throw new Error(`Unknown schema: ${sample.schema}`);
  const check = ajv.getSchema(`aura-analysis#/components/schemas/${sample.schema}`);
  if (!check(sample.value)) throw new Error(`${sample.name}: ${ajv.errorsText(check.errors)}`);
  // OpenAPI permits additive fields by default; still detect undocumented top-level DTO fields.
  const declared = properties(schema);
  const extra = Object.keys(sample.value).filter(key => !(key in declared));
  if (extra.length) throw new Error(`${sample.name}: undocumented response fields: ${extra.join(', ')}`);
}

if (process.argv[2] === '--self-test') {
  for (const [exclusive, bound] of [['exclusiveMinimum', 'minimum'], ['exclusiveMaximum', 'maximum']]) {
    const check = ajv.compile(normalize({ type: 'number', [bound]: 0, [exclusive]: true }));
    assert.equal(check(0), false);
    assert.equal(check(exclusive === 'exclusiveMinimum' ? 1 : -1), true);
    assert.equal(ajv.compile(normalize({ type: 'number', [bound]: 0, [exclusive]: false }))(0), true);
  }
  validate({ name: 'unavailable measurements', schema: 'Metrics', value: {
    vesselDensity: null, tortuosityIndex: null, avRatio: null, fractalDimension: null, branchingPoints: null,
  } });
  const value = { reportId: '11111111-1111-4111-8111-111111111111', format: 'pdf', downloadUrl: '/api/v1/reports/test/content', expiresAt: '2026-11-10T00:00:00Z' };
  validate({ name: 'valid', schema: 'ReportDownload', value });
  assert.throws(() => validate({ name: 'wrong type', schema: 'ReportDownload', value: { ...value, format: 1 } }));
  assert.throws(() => validate({ name: 'bad uuid', schema: 'ReportDownload', value: { ...value, reportId: 'invalid' } }));
  assert.throws(() => validate({ name: 'drift', schema: 'ReportDownload', value: { ...value, undocumented: true } }));
  const missing = { ...value }; delete missing.expiresAt;
  assert.throws(() => validate({ name: 'missing required', schema: 'ReportDownload', value: missing }));
  console.log('PASS: response validator positive/negative self-checks.');
} else {
  if (!process.argv[2]) throw new Error('Pass the response JSON generated by AnalysisContractResponseTests with AURA_M2_ARTIFACTS set.');
  const samples = JSON.parse(fs.readFileSync(process.argv[2], 'utf8').replace(/^\uFEFF/, ''));
  if (!Array.isArray(samples) || !samples.length) throw new Error('Required runtime response samples are missing.');
  const required = ['Analysis', 'AnalysisResult', 'Batch', 'DoctorReview', 'ReportDownload', 'UploadInventory', 'UploadInventoryItem', 'AnalyticsSummary', 'Trends'];
  for (const schema of required) if (!samples.some(sample => sample.schema === schema)) throw new Error(`Missing runtime sample for ${schema}`);
  for (const sample of samples) validate(sample);
  console.log(`PASS: ${samples.length} serialized .NET response samples match OpenAPI types, required fields, enums, formats, references and declared top-level fields.`);
}
